-- Expect: 0 rows.
WITH f     AS (SELECT auth_code / POWER(10, LENGTH(TO_CHAR(auth_code))) AS fr FROM gom_glb_sys.t__CORE_INFO_S),
     conf  AS (SELECT PK FROM BOX_FE.T_BOX_ENGCONF_S   WHERE DESCRIPTION = 'Configuracion -NY'),
     curve AS (SELECT PK FROM BOX_FE.T_BOX_ENGFCURVE_S WHERE DESCRIPTION = 'NY Configuration Suc'),
